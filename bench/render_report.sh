#!/usr/bin/env bash
# Render benchmark report from correctness and speed results
#
# Usage: ./bench/render_report.sh
#
# Outputs: REPORT.md at repo root

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RESULTS_DIR="$REPO_ROOT/results"
OUTPUT="$REPO_ROOT/REPORT.md"

# Discover drafts with results
DRAFTS=$(find "$RESULTS_DIR" -mindepth 1 -maxdepth 1 -type d -exec basename {} \; | sort)

[[ -n "$DRAFTS" ]] || { echo "No results found in $RESULTS_DIR" >&2; exit 1; }

{
    echo "# JSON Schema CLI Benchmark Report"
    echo ""
    echo "Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo ""

    for draft in $DRAFTS; do
        CORRECTNESS="$RESULTS_DIR/$draft/correctness.jsonl"
        SPEED="$RESULTS_DIR/$draft/speed.jsonl"

        echo "## $draft"
        echo ""

        if [[ ! -f "$CORRECTNESS" ]]; then
            echo "_No correctness results._"
            echo ""
            continue
        fi

        # Tools and versions
        echo "### Tools"
        echo ""
        echo "| Tool | Version |"
        echo "|------|---------|"
        jq -r '[.tool, .tool_version] | @tsv' "$CORRECTNESS" | sort -u | while read -r tool version; do
            echo "| $tool | $version |"
        done
        echo ""

        # Correctness summary
        echo "### Correctness"
        echo ""
        total=$(wc -l < "$CORRECTNESS" | tr -d ' ')
        matched=$(jq -c 'select(.match == true)' "$CORRECTNESS" | wc -l | tr -d ' ')
        failed=$(jq -c 'select(.match == false)' "$CORRECTNESS" | wc -l | tr -d ' ')
        echo "- Total checks: $total"
        echo "- Matched: $matched"
        echo "- Mismatched: $failed"
        echo ""

        # Correctness table
        echo "| Tool | Case | Operation | Mode | Outcome | Expected | Match |"
        echo "|------|------|-----------|------|---------|----------|-------|"
        jq -r '[.tool, .case_id, .operation, .mode, .outcome, .expected, .match] | @tsv' "$CORRECTNESS" | while read -r tool case_id op mode outcome expected match; do
            match_icon=$( [[ "$match" == "true" ]] && echo "✓" || echo "✗" )
            echo "| $tool | $case_id | $op | $mode | $outcome | $expected | $match_icon |"
        done
        echo ""

        # Speed summary (if exists)
        if [[ -f "$SPEED" && -s "$SPEED" ]]; then
            echo "### Speed"
            echo ""
            echo "| Tool | Case | Operation | Mode | Mean (s) | Stddev (s) | Min (s) | Max (s) |"
            echo "|------|------|-----------|------|----------|------------|---------|---------|"
            jq -r '[.tool, .case_id, .operation, .mode, (.mean | tostring), (.stddev | tostring), (.min | tostring), (.max | tostring)] | @tsv' "$SPEED" | while read -r tool case_id op mode mean stddev min max; do
                printf "| %s | %s | %s | %s | %.4f | %.4f | %.4f | %.4f |\n" \
                    "$tool" "$case_id" "$op" "$mode" "$mean" "$stddev" "$min" "$max"
            done
            echo ""
        else
            echo "### Speed"
            echo ""
            echo "_No speed results._"
            echo ""
        fi
    done

    echo "---"
    echo ""
    echo "_Report generated by json-schema-cli-benchmark_"

} > "$OUTPUT"

echo "Report written to: $OUTPUT" >&2
